export const formatMeetingDateTime = (timestamp?: number): string => {
  if (!timestamp) return "Not recorded";

  return new Intl.DateTimeFormat(undefined, {
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hourCycle: "h23",
    timeZoneName: "shortOffset",
  }).format(timestamp);
};
